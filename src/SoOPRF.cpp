void SoOPRFRecver::OPRF(std::vector<oc::block> &x, std::vector<oc::block> &y1)
{
    auto r = coproto::sync_wait(coproto::when_all_ready(ole->start(), recver->evaluate(x, y1, *socket, *prng)));

    std::get<0>(r).result();
    std::get<1>(r).result();
}

